import { describe, it, before, after } from "node:test";
import assert from "node:assert/strict";
import { mkdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { randomUUID } from "node:crypto";
import { execFileSync } from "node:child_process";
import { buildRepoBrief, buildRunBrief, summarizeLayout } from "../src/orchestrator/repo-brief.js";

describe("summarizeLayout", () => {
  it("counts files per top-level directory and lists root files", () => {
    const layout = summarizeLayout([
      "package.json",
      "README.md",
      "src/index.ts",
      "src/engine/claude.ts",
      "src/engine/gemini.ts",
      "src/utils/git.ts",
      "test/a.test.ts",
    ]);
    assert.equal(layout, [
      "  src/ (4 files): engine/ (2), utils/ (1)",
      "  test/ (1 file)",
      "  (root) README.md, package.json",
    ].join("\n"));
  });
});

describe("buildRepoBrief", () => {
  let repo: string;
  const git = (...args: string[]) => execFileSync("git", args, { cwd: repo, encoding: "utf-8" }).trim();

  before(async () => {
    repo = join(tmpdir(), `dispatch-brief-${randomUUID()}`);
    await mkdir(join(repo, "src", "engine"), { recursive: true });
    await writeFile(join(repo, "package.json"), JSON.stringify({
      type: "module",
      scripts: { build: "tsc", lint: "tsc --noEmit", test: "node --test" },
      dependencies: { chalk: "^5", commander: "^13" },
      devDependencies: { typescript: "^5" },
    }));
    await writeFile(join(repo, "tsconfig.json"), "{}");
    await writeFile(join(repo, "CLAUDE.md"), "# Conventions\n");
    await writeFile(join(repo, "src", "index.ts"), "export {};\n");
    await writeFile(join(repo, "src", "engine", "claude.ts"), "export {};\n");
    await writeFile(join(repo, "go.mod"), "module x\n");
    git("init", "-q", "-b", "main");
    git("add", ".");
    git("-c", "user.name=T", "-c", "user.email=t@example.com", "commit", "-q", "-m", "init");
    // Untracked files must not appear in the brief
    await writeFile(join(repo, "local-notes.txt"), "secret plans\n");
  });

  after(async () => {
    await rm(repo, { recursive: true, force: true });
  });

  it("describes languages, scripts, docs, entry points, dependencies and layout", async () => {
    const brief = await buildRepoBrief(repo, "HEAD", "npm test");
    assert.ok(brief.startsWith("## Repository brief (generated by Dispatch from HEAD @ "));
    assert.ok(brief.includes("Languages: TypeScript (ESM), Go"));
    assert.ok(brief.includes("Package manager: npm"));
    assert.ok(brief.includes("Verify command: npm test (Dispatch runs it after you finish)"));
    assert.ok(brief.includes('Script "build": tsc'));
    assert.ok(brief.includes('Script "lint": tsc --noEmit'));
    assert.ok(brief.includes("Project instructions: CLAUDE.md"));
    assert.ok(brief.includes("Entry points: src/index.ts"));
    assert.ok(brief.includes("Dependencies: chalk, commander"));
    assert.ok(brief.includes("Layout (6 tracked files):"));
    assert.ok(brief.includes("src/ (2 files): engine/ (1)"));
    assert.ok(!brief.includes("(1 files)"));
  });

  it("only includes committed files", async () => {
    const brief = await buildRepoBrief(repo, "HEAD", null);
    assert.ok(!brief.includes("local-notes.txt"));
    assert.ok(brief.includes("Verify command: none configured"));
  });

  it("is deterministic for the same commit", async () => {
    assert.equal(await buildRepoBrief(repo, "HEAD", "npm test"), await buildRepoBrief(repo, "HEAD", "npm test"));
  });

  it("caps its size on large repositories", async () => {
    for (let d = 0; d < 300; d++) {
      await mkdir(join(repo, `pkg${d}`), { recursive: true });
      await writeFile(join(repo, `pkg${d}`, "index.ts"), "export {};\n");
    }
    git("add", ".");
    git("-c", "user.name=T", "-c", "user.email=t@example.com", "commit", "-q", "-m", "many dirs");
    const brief = await buildRepoBrief(repo, "HEAD", "npm test");
    assert.ok(brief.length <= 4100, `length ${brief.length}`);
    assert.ok(brief.endsWith("… (truncated)"));
  });

  it("falls back to the local base branch without a remote", async () => {
    const result = await buildRunBrief(repo, "main", "npm test");
    assert.equal(result?.ref, "main");
    assert.ok(result?.brief.includes("from main @ "));
  });
});
