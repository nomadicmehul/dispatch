import { git } from "../utils/git.js";
import { log } from "../utils/logger.js";

/**
 * A short, deterministic description of the repository that every agent session in a
 * run receives, so agents don't each spend turns re-exploring the same layout.
 * Built from the base branch with git (committed files only), with no AI call.
 */

const MAX_BRIEF_CHARS = 4000;
const MAX_DEPENDENCIES = 40;

const AGENT_DOCS = ["CLAUDE.md", "AGENTS.md", "CONTRIBUTING.md", ".github/copilot-instructions.md"];
const ENTRY_POINTS = [
  "src/index.ts", "src/index.js", "src/main.ts", "src/main.js", "src/app.ts", "src/app.js",
  "main.go", "cmd/main.go", "src/main.rs", "src/lib.rs", "main.py", "app.py",
];

interface Manifest {
  languages: string[];
  packageManager?: string;
  scripts: Record<string, string>;
  dependencies: string[];
}

/** Summarize files per directory: top-level directories with counts, and their largest subdirectories */
export function summarizeLayout(files: string[]): string {
  const rootFiles: string[] = [];
  const topLevel = new Map<string, { count: number; children: Map<string, number> }>();

  for (const file of files) {
    const parts = file.split("/");
    if (parts.length === 1) {
      rootFiles.push(file);
      continue;
    }
    const dir = topLevel.get(parts[0]) ?? { count: 0, children: new Map<string, number>() };
    dir.count++;
    if (parts.length > 2) dir.children.set(parts[1], (dir.children.get(parts[1]) ?? 0) + 1);
    topLevel.set(parts[0], dir);
  }

  const lines: string[] = [];
  const dirs = [...topLevel.entries()].sort((a, b) => b[1].count - a[1].count);
  for (const [name, dir] of dirs) {
    const children = [...dir.children.entries()]
      .sort((a, b) => b[1] - a[1])
      .slice(0, 8)
      .map(([child, count]) => `${child}/ (${count})`);
    lines.push(`  ${name}/ (${dir.count} file${dir.count === 1 ? "" : "s"})${children.length ? `: ${children.join(", ")}` : ""}`);
  }
  if (rootFiles.length > 0) {
    lines.push(`  (root) ${rootFiles.sort().join(", ")}`);
  }
  return lines.join("\n");
}

/** Detect languages, package manager, scripts and dependencies from manifest files */
async function readManifests(files: Set<string>, show: (path: string) => Promise<string | null>): Promise<Manifest> {
  const manifest: Manifest = { languages: [], scripts: {}, dependencies: [] };

  if (files.has("package.json")) {
    try {
      const pkg = JSON.parse((await show("package.json")) ?? "{}") as {
        type?: string;
        scripts?: Record<string, string>;
        dependencies?: Record<string, string>;
        devDependencies?: Record<string, string>;
      };
      const typescript = files.has("tsconfig.json") || Boolean(pkg.devDependencies?.typescript || pkg.dependencies?.typescript);
      manifest.languages.push(`${typescript ? "TypeScript" : "JavaScript"} (${pkg.type === "module" ? "ESM" : "CommonJS"})`);
      manifest.scripts = pkg.scripts ?? {};
      manifest.dependencies = Object.keys(pkg.dependencies ?? {});
    } catch {
      manifest.languages.push("JavaScript");
    }
    manifest.packageManager = files.has("pnpm-lock.yaml") ? "pnpm"
      : files.has("yarn.lock") ? "yarn"
      : files.has("bun.lockb") || files.has("bun.lock") ? "bun"
      : "npm";
  }
  if (files.has("go.mod")) manifest.languages.push("Go");
  if (files.has("Cargo.toml")) manifest.languages.push("Rust");
  if (files.has("pyproject.toml") || files.has("requirements.txt") || files.has("setup.py")) manifest.languages.push("Python");
  if (files.has("Gemfile")) manifest.languages.push("Ruby");
  if (files.has("pom.xml") || files.has("build.gradle") || files.has("build.gradle.kts")) manifest.languages.push("Java/Kotlin");

  return manifest;
}

/**
 * Build the brief for `ref` (normally origin/<baseBranch>).
 * `verifyCommand` is the command Dispatch will run after the agent finishes.
 */
export async function buildRepoBrief(
  cwd: string,
  ref: string,
  verifyCommand: string | null,
): Promise<string> {
  const { stdout: listing } = await git(["ls-tree", "-r", "--name-only", ref], cwd);
  const fileList = listing.split("\n").filter(Boolean);
  const files = new Set(fileList);
  const { stdout: sha } = await git(["rev-parse", "--short", ref], cwd);

  const show = async (path: string): Promise<string | null> => {
    try {
      return (await git(["show", `${ref}:${path}`], cwd)).stdout;
    } catch {
      return null;
    }
  };

  const manifest = await readManifests(files, show);
  const scriptNames = ["build", "lint", "typecheck", "format"].filter((s) => manifest.scripts[s]);

  const lines = [
    `## Repository brief (generated by Dispatch from ${ref} @ ${sha})`,
    "A summary of this repository so you can skip broad exploration. Read files directly when you need details.",
    "",
  ];
  if (manifest.languages.length) lines.push(`Languages: ${manifest.languages.join(", ")}`);
  if (manifest.packageManager) lines.push(`Package manager: ${manifest.packageManager}`);
  lines.push(`Verify command: ${verifyCommand ?? "none configured"}${verifyCommand ? " (Dispatch runs it after you finish)" : ""}`);
  for (const name of scriptNames) {
    lines.push(`Script "${name}": ${manifest.scripts[name]}`);
  }

  const docs = AGENT_DOCS.filter((f) => files.has(f));
  if (docs.length) lines.push(`Project instructions: ${docs.join(", ")} (follow their conventions)`);
  const entries = ENTRY_POINTS.filter((f) => files.has(f));
  if (entries.length) lines.push(`Entry points: ${entries.join(", ")}`);

  if (manifest.dependencies.length) {
    const shown = manifest.dependencies.slice(0, MAX_DEPENDENCIES);
    const more = manifest.dependencies.length - shown.length;
    lines.push(`Dependencies: ${shown.join(", ")}${more > 0 ? ` (+${more} more)` : ""}`);
  }

  lines.push("", `Layout (${fileList.length} tracked files):`, summarizeLayout(fileList));

  const brief = lines.join("\n");
  return brief.length > MAX_BRIEF_CHARS
    ? `${brief.slice(0, MAX_BRIEF_CHARS)}\n  … (truncated)`
    : brief;
}

/** Build the brief for the base branch, or return undefined if it can't be built */
export async function buildRunBrief(
  cwd: string,
  baseBranch: string,
  verifyCommand: string | null,
): Promise<{ brief: string; ref: string } | undefined> {
  try {
    await git(["fetch", "origin", baseBranch], cwd);
  } catch {
    // Offline or no remote: use whatever ref resolves below
  }

  let ref = "HEAD";
  for (const candidate of [`origin/${baseBranch}`, baseBranch]) {
    try {
      await git(["rev-parse", "--verify", "--quiet", `${candidate}^{commit}`], cwd);
      ref = candidate;
      break;
    } catch {
      // try the next candidate
    }
  }

  try {
    return { brief: await buildRepoBrief(cwd, ref, verifyCommand), ref };
  } catch (err) {
    log.warn(`Could not build the repository brief: ${err instanceof Error ? err.message : err}`);
    return undefined;
  }
}
